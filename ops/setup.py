"""Guided local configuration. Never deploy or change existing services implicitly."""
import argparse
import getpass
import json
import os
from pathlib import Path
import secrets
import subprocess
import tempfile
from urllib.parse import urlsplit
from urllib.request import Request, urlopen
from urllib.error import HTTPError, URLError


def quote(value):
    if any(c in value for c in "\r\n\0"):
        raise ValueError("Configuration values must be single-line")
    return "'" + value.replace("'", "\\'") + "'"


def read_env(path):
    result = {}
    if not path.exists():
        return result
    for line in path.read_text(encoding="utf-8").splitlines():
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        key, value = line.split("=", 1)
        value = value.strip()
        if value.startswith("'") and value.endswith("'"):
            value = value[1:-1].replace("\\'", "'")
        elif value.startswith('"') and value.endswith('"'):
            value = json.loads(value)
        result[key.strip()] = value
    return result


def write_env(path, values):
    # Replace atomically, preserving the existing file until every answer is valid.
    fd, name = tempfile.mkstemp(prefix=".glaze-env-", dir=path.parent)
    try:
        with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as file:
            file.write("# Generated by Glaze setup. Keep private; never commit.\n")
            file.writelines(f"{key}={quote(value)}\n" for key, value in values.items())
        os.replace(name, path)
    finally:
        if os.path.exists(name):
            os.unlink(name)


def ask(label, default="", secret=False, required=True):
    while True:
        hint = " [Enter to keep existing]" if secret and default else f" [{default}]" if default else ""
        value = (getpass.getpass if secret else input)(label + hint + ": ")
        value = value or default
        if not required or value:
            if any(c in value for c in "\r\n\0"):
                print("Enter a single-line value.")
                continue
            return value
        print("This value is required.")


def yes_no(label, default="no"):
    while True:
        value = ask(label + " yes/no", default).lower()
        if value in ("yes", "no"):
            return value == "yes"
        print("Choose yes or no.")


def address(label, default):
    while True:
        value = ask(label, default).rstrip("/")
        parts = urlsplit(value)
        if parts.scheme in ("http", "https") and parts.hostname and not parts.username and not parts.query and not parts.fragment:
            return value
        print("Use an HTTP(S) base address without embedded credentials or query parameters.")


def check(values):
    if not values.get("COMPANION_API_TOKEN"):
        print("Run setup first to create your private .env.")
        return False
    request = Request("http://127.0.0.1:" + values.get("COMPANION_PORT", "8088") + "/health",
                      headers={"Authorization": "Bearer " + values["COMPANION_API_TOKEN"]})
    try:
        try:
            response = urlopen(request, timeout=15)
        except HTTPError as error:
            response = error
        with response:
            report = json.load(response)
        for name, dependency in report.get("dependencies", {}).items():
            print(("OK " if dependency.get("authenticated") else "FAIL ") + name +
                  ("" if dependency.get("authenticated") else ": check its address and credentials"))
        if "state_writable" in report:
            print(("OK " if report["state_writable"] else "FAIL ") + "Companion state folder permissions")
        if report.get("downloads_enabled"):
            for name in ("library", "downloads"):
                print(("OK " if report.get(name + "_writable") else "FAIL ") + name +
                      " folder permissions inside Companion")
        else:
            print("Downloads disabled — no slskd or media mounts required.")
        return report.get("status") == "ok"
    except (URLError, ValueError, KeyError):
        print("Companion could not be checked. Start it and run this helper with --check.")
        return False


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Check the running container without changing configuration")
    args = parser.parse_args()
    root = Path(__file__).resolve().parent.parent
    path = root / ".env"
    values = read_env(path)
    if args.check:
        raise SystemExit(0 if check(values) else 1)
    if path.exists() and not yes_no("Update existing .env?"):
        print("Existing configuration preserved.")
        return
    values.setdefault("COMPANION_API_TOKEN", secrets.token_hex(32))
    if len(values["COMPANION_API_TOKEN"]) < 32 or values["COMPANION_API_TOKEN"].startswith("replace-"):
        values["COMPANION_API_TOKEN"] = secrets.token_hex(32)
    values.setdefault("COMPANION_BIND_ADDRESS", "127.0.0.1")
    values.setdefault("COMPANION_PORT", "8088")
    values["DOCKER_NETWORK"] = ask("Docker network name (existing media network, or a new network for a remote Navidrome)", values.get("DOCKER_NETWORK", "glaze"))
    values["NAVIDROME_API_URL"] = address("Navidrome address reachable inside Companion", values.get("NAVIDROME_API_URL", "http://navidrome:4533"))
    values["NAVIDROME_USERNAME"] = ask("Navidrome username for server checks", values.get("NAVIDROME_USERNAME", ""))
    values["NAVIDROME_PASSWORD"] = ask("Navidrome password", values.get("NAVIDROME_PASSWORD", ""), secret=True)
    enabled = yes_no("Enable server-side downloads?", "yes" if values.get("DOWNLOADS_ENABLED") == "true" else "no")
    values["DOWNLOADS_ENABLED"] = str(enabled).lower()
    if enabled:
        values["SLSKD_API_URL"] = address("slskd address reachable inside Companion", values.get("SLSKD_API_URL", "http://slskd:5030"))
        mode = ask("slskd authentication: key or credentials", "key" if values.get("SLSKD_API_KEY") else "credentials")
        while mode not in ("key", "credentials"):
            mode = ask("Choose key or credentials")
        if mode == "key":
            values["SLSKD_API_KEY"] = ask("slskd API key", values.get("SLSKD_API_KEY", ""), secret=True)
            values["SLSKD_USERNAME"] = values["SLSKD_PASSWORD"] = ""
        else:
            values["SLSKD_API_KEY"] = ""
            values["SLSKD_USERNAME"] = ask("slskd WEB username (not Soulseek)", values.get("SLSKD_USERNAME", ""))
            values["SLSKD_PASSWORD"] = ask("slskd WEB password", values.get("SLSKD_PASSWORD", ""), secret=True)
        for key, label in (("NAVIDROME_LIBRARY_HOST_PATH", "Navidrome music folder on this server"),
                           ("SLSKD_DOWNLOAD_HOST_PATH", "slskd completed-download folder on this server")):
            while True:
                folder = ask(label, values.get(key, ""))
                if Path(folder).is_absolute() and Path(folder).is_dir():
                    values[key] = folder
                    break
                print("Choose an existing absolute directory. No folders or permissions will be changed.")
        for key in ("COMPANION_UID", "COMPANION_GID"):
            native_id = getattr(os, "getuid" if key.endswith("UID") else "getgid", lambda: 10001)()
            value = ask(key + " of your media account", values.get(key, str(native_id)))
            while not value.isdigit() or value == "0":
                value = ask("Enter the numeric ID of a non-root media account")
            values[key] = value
        values["NAVIDROME_LIBRARY_PATH"], values["SLSKD_DOWNLOAD_PATH"] = "/music", "/downloads"
        if yes_no("Also enable Qobuz downloads?", "yes" if values.get("QOBUZ_USERNAME") else "no"):
            values["QOBUZ_USERNAME"] = ask("Qobuz username", values.get("QOBUZ_USERNAME", ""))
            values["QOBUZ_PASSWORD"] = ask("Qobuz password", values.get("QOBUZ_PASSWORD", ""), secret=True)
            first = ask("Optional first source: slskd or qobuz", values.get("ACQUISITION_PROVIDER_ORDER", "slskd,qobuz").split(",")[0]).lower()
            while first not in ("slskd", "qobuz"):
                first = ask("Choose slskd or qobuz", "slskd").lower()
            values["ACQUISITION_PROVIDER_ORDER"] = first + (",qobuz" if first == "slskd" else ",slskd")
        else:
            values["QOBUZ_USERNAME"] = values["QOBUZ_PASSWORD"] = ""
            values.setdefault("ACQUISITION_PROVIDER_ORDER", "slskd,qobuz")
        values["ACOUSTID_API_KEY"] = ask("Optional AcoustID application key (Enter to skip)", values.get("ACOUSTID_API_KEY", ""), secret=True, required=False)
    if not enabled:
        values["COMPANION_UID"] = values["COMPANION_GID"] = "10001"
    values["LASTFM_API_KEY"] = ask("Optional Last.fm metadata API key (Enter to skip)", values.get("LASTFM_API_KEY", ""), secret=True, required=False)
    write_env(path, values)
    command = ["docker", "compose", "-f", "compose.jam.yaml"]
    if enabled:
        command += ["-f", "compose.downloads.yaml"]
    command += ["up", "-d", "--build"]
    print("Private .env saved. Start Companion with:\n" + " ".join(command))
    print("Your existing Navidrome/slskd services are preserved. Configure HTTPS and WebSocket forwarding for phone access.")
    if yes_no("Start Companion now?"):
        network = values["DOCKER_NETWORK"]
        found = subprocess.run(["docker", "network", "inspect", network], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        if found.returncode != 0:
            subprocess.run(["docker", "network", "create", network], check=True)
        subprocess.run(command, cwd=root, check=True)
        print("Run python3 ops/setup.py --check once the container has started.")


if __name__ == "__main__":
    main()
